# FIXME could break apart and refactor into a set of functions following an interface and a map of action->function
function doAction {
	local arr=("$@")
	local context="${arr[0]}"
	local action="${arr[1]}"
	local args="${arr[@]:2}"
	# TODO need to add error handling.
	local errorMsg
	case "$action" in
	c)
		echo "$args"
		if [[ -f "$context/$args" ]]; then
			commentOutput < <(cat -n "$context/$args")
		elif [[ -d "$context/$args" ]]; then
			: echo "| $args is a directory" >&2
		else
			: echo "| $context/$args doesn't exist" >&2
		fi

		;;
	s)
		local statArgs=($args)
		echo "${statArgs[0]}"
		commentOutput < <(stat "$context/${statArgs[0]}")
		;;
	p)
		local pathArgs=($args)
		echo "${pathArgs[0]}"
		commentOutput < <(echo "$context/${pathArgs[0]}")
		;;
	f)
		local searchArgs=($args)
		populateSearch "$context" "$searchArgs"
		echo "| (f) $searchArgs" # TODO keeping original argument in order as is.
		;;
	h)
		local headArgs=($args)
		echo "${headArgs[1]}"
		commentOutput < <(head -n "${headArgs[0]}" "$context/${headArgs[1]}")
		;;
	t)
		local tailArgs=($args)
		echo "${tailArgs[1]}"
		commentOutput < <(tail -n "${tailArgs[0]}" "$context/${tailArgs[1]}")
		;;
	r)
		local rangeArgs=($args)
		echo "${rangeArgs[2]}"
		commentOutput < <(cat -n "$context/${rangeArgs[2]}" | head -n "${rangeArgs[1]}" | tail -n $((${rangeArgs[1]} - ${rangeArgs[0]})))
		;;
	to)
		touch "$context/$args"
		echo "$args"
		;;
	cp)
		echo "| copied $args"
		local copyArgs=($args)
		if [[ -f "$context/${copyArgs[0]}" ]]; then
			# TODO need to add logic to check if target has '/' or not to determine where the file is going in regards to the project.
			cp "$context/${copyArgs[0]}" "${copyArgs[1]}"
		elif [[ -d "$context/${copyArgs[0]}" ]]; then
			echo "| Arg 0 '${copyArgs[0]}' is a directory, use the cpr command to copy"
		else
			echo "| File '${copyArgs[0]}' doesn't exist"
		fi
		;;
	cpr)
		local copyArgs=($args)
		if [[ -d "$context/${copyArgs[0]}" ]]; then
			cp -r "$context/${copyArgs[0]}" "${copyArgs[1]}"
		elif [[ -f "$context/${copyArgs[0]}" ]]; then
			echo "| Arg 0 '${copyArgs[0]}' is a directory, use the cpr command to copy"
		else
			echo "| File '${copyArgs[0]}' doesn't exist"
		fi
		;;
	n)
		local renameArgs=($args)
		if [[ -f "$context/${renameArgs[0]}" ]]; then
			if [[ -f "$context/${renameArgs[1]}" ]]; then
				echo "${renameArgs[0]}"
				echo "| File '${renameArgs[1]}' already exists"
			else
				echo "${renameArgs[1]}"
				mv "$context/${renameArgs[0]}" "$context/${renameArgs[1]}"
			fi
		elif [[ -d "$context/${renameArgs[0]}" ]]; then
			if [[ -d "$context/${renameArgs[1]}" ]]; then
				echo "${renameArgs[0]}"
				echo "| Dir '${renameArgs[1]}' already exists"
			else
				echo "${renameArgs[1]}"
				mv "$context/${renameArgs[0]}" "$context/${renameArgs[1]}"
			fi
		else
			echo "| Source file or dir '${renameArgs[0]}' doesn't exist"
		fi
		;;
	mv)
		# TODO need to update the location output for new file if moved under new parent
		# TODO logic here needs to be a little more complex
		local moveArgs=($args)
		if [[ -f "$context/${moveArgs[0]}" ]]; then
			if [[ -f "${moveArgs[1]}" ]]; then
				echo "| File '${moveArgs[1]}' already exists"
			else
				# TODO need to check if target contains '/' then no change otherwise
				mv "$context/${moveArgs[0]}" "${moveArgs[1]}"
			fi
		elif [[ -d "$context/${moveArgs[0]}" ]]; then
			if [[ -d "${moveArgs[1]}" ]]; then
				echo "| Dir '${moveArgs[1]}' already exists"
			else
				# TODO need to check if target contains '/' then no change otherwise
				mv "$context/${moveArgs[0]}" "${moveArgs[1]}"
			fi
		else
			echo "| File '${moveArgs[0]}' doesn't exist"
		fi
		;;
	mk)
		local mkdirArgs=($args)
		for ((i = 0; i < ${#mkdirArgs[@]}; i++)); do
			if [[ -d "$context/${mkdirArgs[i]}" ]]; then
				echo "| Dir '${mkdirArgs[i]}' already exists"
			else
				mkdir -p "$context/${mkdirArgs[i]}"
				echo "${mkdirArgs[i]}"
			fi
		done
		;;
	d)
		if [[ -f "$context/$args" ]]; then
			errorMsg="$(rm "$context/$args")"
			echo "| deleted $args"
		else
			echo "| Failed to delete $args"
			commentOutput < <(echo "$errorMsg")
		fi
		;;
	dr)
		if [[ -d "$context/$args" ]]; then
			errorMsg="$(rm -r "$context/$args")"
			echo "| deleted $context/$args"
		else
			echo "| Failed to delete $context/$args"
			commentOutput < <(echo "$errorMsg")
		fi
		;;
		# TODO implement (q) and (a) confirmation prompts
	*)
		echo "| Unknown operation: $action" >&2
		;;
	esac
}

function processGlobalConfig {

	# config defaults
	globals['comments']=discard
	globals['path']=short
	globals['hidden']=display
	globals['emitTokens']=off

	if [[ -f "$configFile" ]]; then
		while IFS=$'\n' read -r line; do
			# Extract config line key and value
			if [[ "$line" =~ ^(.*)\ =\ (.*) ]]; then
				local prop="${BASH_REMATCH[1]}"
				local val="${BASH_REMATCH[2]}"
				# Check if config line is commented out
				if [[ ! "$line" =~ ^[#] ]]; then
					# TODO skipping config validation for prototype
					globals["$prop"]="$val"
				fi
			fi
		done < <(cat "$configFile")
	else
		echo "| no config file: $configFile"
	fi
}

# TODO cleanup and refactor, got escaping whitespacing working, but most likely broke something else
function listDir {
	local findQuery
	if [[ -n "${globals[excludeDir]}" ]]; then
		for d in $(echo "${globals[excludeDir]}" | xargs printf $'"%s"\n'); do
			findQuery="${findQuery}-type d -name ${d//\"/\'} -prune -o "
		done
	fi

	if [[ -n "${globals[excludeFile]}" ]]; then
		for f in $(echo "${globals[excludeFile]}" | xargs printf $'"%s"\n'); do
			findQuery="${findQuery}-type f -name ${f//\"/\'} -prune -o "
		done
	fi

	findQuery="find . ${findQuery}-type d -print0 -o -type f -print0"
	: echo "| $findQuery"

	declare -A aggregate
	while IFS= read -r -d '' line; do
		local dName fName
		if [[ -d $line ]]; then
			# TODO check if dir entry already exists (it shouldn't, unless I mess something up)
			# Create dir entry and append dir to parent entry, if exists...
			# FIXME need to escape whitespace
			dName="$(dirname "$line")"
			fName="$(basename "$line")"
			aggregate["${line// /\\ }"]=''
			if [[ "$fName" == '.' && "$dName" == '.' ]]; then
				: echo "| fName matched '.' "
			else
				aggregate[${dName// /\\ }]="${aggregate[${dName// /\\ }]}${fName// /\\ }
"
			fi
		elif [[ -f $line ]]; then
			# Append file entry to dir
			dName="$(dirname "$line")"
			fName="$(basename "$line")"
			aggregate[${dName// /\\ }]="${aggregate[${dName// /\\ }]}${fName// /\\ }
"
		else
			echo "| don't know: ${line// /\\ }" >&2
		fi
	done < <(eval "$findQuery" | sort -d -z)

	# TODO might have to utilize zero byte delimeter for these operations
	local keys=$(echo "${!aggregate[*]}" | xargs printf $'%s\n' | sort -d)
	IFS=$'\n'
	for key in $keys; do
		echo "${key// /\\ }:"
		echo "${aggregate[${key// /\\ }]}" | xargs printf $'%s\n' | sort | sed -s 's/ /\\ /g'
		echo
	done
}

function processOverrideTokens {
	local token="$1"
	local configKey configValue
	if [[ "$token" =~ ^\<context:\ (.*)\ \{Override\}\>(.*)\ (.*)$ ]]; then
		configKey="${BASH_REMATCH[2]}"
		configValue="${BASH_REMATCH[3]}"
		globals[$configKey]="$configValue"
		if [[ "${globals['emitTokens']}" == 'on' ]]; then
			echo "$token"
		fi
	elif [[ "$token" =~ ^\<context:\ (.*)\ \{OverrideRepeat\}\>(.*)\ (.*)$ ]]; then
		configKey="${BASH_REMATCH[2]}"
		configValue="${BASH_REMATCH[3]}"
		globals[$configKey]="$configValue"
		if [[ "${globals['emitTokens']}" == 'on' ]]; then
			echo "$token"
		else
			echo "(!cr) ${configKey}=${configValue}"
		fi
	fi
}

function processCommentTokens {
	local token="$1"
	if [[ "$token" =~ ^\<context:\ (.*)\ \{Comment\}\>(.*)$ ]]; then
		if [[ "${globals[comments]}" == 'keep' ]]; then
			echo "| ${BASH_REMATCH[2]}"
		fi
	fi
}

function processActionTokens {
	local token="$1"
	local context action args
	if [[ "$token" =~ ^\<context:\ (.*)\ \{Action\}\>(.*)\ (.*)$ ]]; then
		context="${BASH_REMATCH[1]}"
		action="${BASH_REMATCH[2]}"
		args="${BASH_REMATCH[3]}"
		doAction "$context" "$action" $args
	fi
}

function main {
	if [[ "$1" == "help" ]]; then
		helpDoc
		return 0
	fi

	if [[ "$1" == '-t' ]]; then
		globals['emitTokens']='on'
	fi

	# TODO add support for flag to generate new output
	# TODO add support for reading from file in arguments
	# TODO add flag to emit just tokenized output for debugging purposes.

	processGlobalConfig
	local lineRead

	if [[ -t 0 ]]; then
		listDir
	else
		# FIXME ideally processOverrideTokens should happens over the whole stream prior to evaluating them, but whatever.
		while read -r token; do
			[[ -z "$lineRead" ]] && lineRead=true
			if [[ "${globals['emitTokens']}" == 'on' ]]; then
				echo "$token"
			else
				# TODO could refactor to match on type first, then use regex to extract necessary values
				processOverrideTokens "$token"
				processCommentTokens "$token"
				processActionTokens "$token"

				if [[ "$token" =~ ^\<context:\ (.*)\ \{Dir}\>(.*)$ ]]; then
					# Note: just matching non actionable token
					echo "${BASH_REMATCH[1]}:"
				elif [[ "$token" =~ ^\<context:\ (.*)\ \{Entry}\>(.*)$ ]]; then

					# print out results in format configured
					if [[ "${globals['path']}" == 'relative' ]]; then
						echo "${BASH_REMATCH[1]}/${BASH_REMATCH[2]}"
					else
						echo "${BASH_REMATCH[2]}"
					fi

					# mixin search results if matching result is found
					local searchKey="${BASH_REMATCH[1]}/${BASH_REMATCH[2]}"
					[[ -n "$searchKey" ]] && local searchOutput="${searchResults["$searchKey"]}"
					if [[ -n "$searchOutput" ]]; then
						commentOutput < <(echo "$searchOutput")
					fi

				elif [[ "$token" =~ ^\<context:\ (.*)\ \{Empty\}\>$ ]]; then
					echo
				fi
			fi
		done < <(tokenizeInput)
		if [[ ! "$lineRead" ]]; then
			listDir
		fi
	fi
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
	main "$@"
fi

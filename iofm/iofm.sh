function tokenizeInput {
	# TODO if I need to output a confirmation, could utilize |? $Question: Y/N
	#      token format would be <context: $context {Confirmation} {$previousToken} {$answer}>$question
	local currentContext firstArg remainingArgs

	while IFS=$'\n' read -r line; do
		if [[ "$line" =~ ^\<context:\ .*\ \{.*\}\>.*$ ]]; then
			# input matches token, so just re-emitting token
			echo "$line"
		elif [[ "$line" =~ ^\(\!c\)\ (.*)[=](.*)$ ]]; then

			# tokenize local config
			echo "<context: $currentContext {Override}>${BASH_REMATCH[1]} ${BASH_REMATCH[2]}"

		elif [[ "$line" =~ ^\(!cr\)\ (.*)[=](.*)$ ]]; then

			# tokenize repeating override
			echo "<context: $currentContext {OverrideRepeat}>${BASH_REMATCH[1]} ${BASH_REMATCH[2]}"

		elif [[ "$line" =~ ^([.].*)[:]$ ]]; then

			# tokenize directory and set the current context for the next set of entries
			currentContext="${BASH_REMATCH[1]}"
			echo "<context: $currentContext {Dir}>"

		elif [[ "$line" =~ ^[\|]\ (.*)$ ]]; then

			# tokenize commented line
			echo "<context: $currentContext {Comment}>${BASH_REMATCH[1]}"

		elif [[ "$line" =~ ^[\(](.+)[\)]\ (.+)\ ?(.+)?$ ]]; then

			# tokenize file system action
			firstArg="$(basename ${BASH_REMATCH[2]})"
			remainingArgs="${BASH_REMATCH[3]}"
			echo "<context: $currentContext {Action}>${BASH_REMATCH[1]} $firstArg $remainingArgs"

		elif [[ "$line" =~ ^\s*$ ]]; then

			echo "<context: $currentContext {Empty}>"

		else

			# tokenize dir entry
			firstArg="$(basename $line)"
			echo "<context: $currentContext {Entry}>$firstArg"

		fi
	done
}

function commentOutput {
	while IFS=$'\n' read -r line; do
		echo "| $line"
	done
}

